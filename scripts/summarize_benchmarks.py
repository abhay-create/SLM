#!/usr/bin/env python3
"""
Summarize TrainingLogger CSV files into publication-friendly benchmark tables.

This script intentionally uses only the Python standard library so it can run on
the same SSH machines as training without extra dependencies.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path
from statistics import median
from typing import Any


DOMAIN_KEYS = ("s0", "s1", "s2", "roc", "simple", "child", "wp")


def parse_float(value: Any) -> float:
    try:
        if value in (None, ""):
            return float("nan")
        return float(value)
    except (TypeError, ValueError):
        return float("nan")


def finite_values(rows: list[dict[str, str]], column: str) -> list[float]:
    values = [parse_float(row.get(column)) for row in rows]
    return [value for value in values if math.isfinite(value)]


def fmt(value: float, digits: int = 4) -> str:
    if not math.isfinite(value):
        return ""
    return f"{value:.{digits}f}"


def fmt_pct(value: float) -> str:
    if not math.isfinite(value):
        return ""
    return f"{value * 100:.2f}%"


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def metric_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    return [
        row
        for row in rows
        if row.get("step") not in (None, "")
        and not str(row.get("note", "")).startswith("EXIT:")
        and row.get("train_loss") not in (None, "")
    ]


def summarize_file(path: Path) -> dict[str, Any] | None:
    rows = read_rows(path)
    data_rows = metric_rows(rows)
    if not data_rows:
        return None

    last = data_rows[-1]
    current_vals = finite_values(data_rows, "current_val")
    train_losses = finite_values(data_rows, "train_loss")
    interval_tps = finite_values(data_rows, "interval_tokens_per_sec")
    replay_values = finite_values(data_rows, "replay_frac")
    forgetting_values = finite_values(data_rows, "ts_forgetting")
    gpu_peak_values = finite_values(data_rows, "gpu_mem_peak_mb")

    domains: dict[str, dict[str, float]] = {}
    for key in DOMAIN_KEYS:
        losses = finite_values(data_rows, f"val_{key}")
        if losses:
            domains[key] = {
                "best_loss": min(losses),
                "latest_loss": parse_float(last.get(f"val_{key}")),
                "latest_ppl": parse_float(last.get(f"ppl_{key}")),
            }

    return {
        "log_file": str(path),
        "stage": last.get("stage", ""),
        "rows": len(data_rows),
        "last_step": int(parse_float(last.get("step"))),
        "tokens_seen": int(parse_float(last.get("tokens_seen"))),
        "tokens_seen_m": parse_float(last.get("tokens_seen")) / 1_000_000,
        "val_key": last.get("val_key", ""),
        "latest_train_loss": train_losses[-1] if train_losses else float("nan"),
        "latest_current_val": current_vals[-1] if current_vals else float("nan"),
        "best_current_val": min(current_vals) if current_vals else float("nan"),
        "latest_forgetting": forgetting_values[-1] if forgetting_values else float("nan"),
        "peak_forgetting": max(forgetting_values) if forgetting_values else float("nan"),
        "peak_replay_frac": max(replay_values) if replay_values else float("nan"),
        "median_interval_tokens_per_sec": median(interval_tps) if interval_tps else float("nan"),
        "peak_gpu_mem_mb": max(gpu_peak_values) if gpu_peak_values else float("nan"),
        "domains": domains,
    }


def discover_logs(log_dirs: list[str]) -> list[Path]:
    paths: list[Path] = []
    for log_dir in log_dirs:
        root = Path(log_dir)
        if root.exists():
            paths.extend(sorted(root.glob("stage*.csv")))
    return sorted(set(paths))


def write_markdown(summaries: list[dict[str, Any]], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Benchmark Summary",
        "",
        "Generated by `scripts/summarize_benchmarks.py` from `TrainingLogger` CSV files.",
        "",
    ]

    if not summaries:
        lines.extend(
            [
                "No training CSV logs were found.",
                "",
                "Run a curriculum or expansion stage, then re-run this script.",
                "",
            ]
        )
        output.write_text("\n".join(lines), encoding="utf-8")
        return

    lines.extend(
        [
            "## Run Overview",
            "",
            "| Stage | Rows | Last Step | Tokens (M) | Val Key | Latest Train | Best Current Val | Latest Forgetting | Peak Replay | Median Tok/s | Peak GPU MB | Log |",
            "|---|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---|",
        ]
    )
    for summary in summaries:
        lines.append(
            "| {stage} | {rows} | {last_step} | {tokens_m} | {val_key} | "
            "{train} | {best_val} | {forgetting} | {replay} | {tok_s} | {gpu} | `{log}` |".format(
                stage=summary["stage"],
                rows=summary["rows"],
                last_step=summary["last_step"],
                tokens_m=fmt(summary["tokens_seen_m"], 1),
                val_key=summary["val_key"],
                train=fmt(summary["latest_train_loss"], 4),
                best_val=fmt(summary["best_current_val"], 4),
                forgetting=fmt_pct(summary["latest_forgetting"]),
                replay=fmt(summary["peak_replay_frac"], 3),
                tok_s=fmt(summary["median_interval_tokens_per_sec"], 1),
                gpu=fmt(summary["peak_gpu_mem_mb"], 1),
                log=summary["log_file"],
            )
        )

    lines.extend(["", "## Per-Domain Best Losses", ""])
    for summary in summaries:
        lines.extend(
            [
                f"### {summary['stage']} - `{summary['log_file']}`",
                "",
                "| Domain | Best Loss | Latest Loss | Latest PPL |",
                "|---|---:|---:|---:|",
            ]
        )
        for key, metrics in summary["domains"].items():
            lines.append(
                f"| `{key}` | {fmt(metrics['best_loss'])} | "
                f"{fmt(metrics['latest_loss'])} | {fmt(metrics['latest_ppl'], 2)} |"
            )
        lines.append("")

    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Summarize training benchmark CSV logs.")
    parser.add_argument(
        "--log-dir",
        action="append",
        help="Directory containing TrainingLogger CSVs. Can be repeated. Defaults to logs and Logs.",
    )
    parser.add_argument(
        "--output",
        default="docs/benchmark_summary.md",
        help="Markdown summary path.",
    )
    parser.add_argument(
        "--json-output",
        default=None,
        help="Optional JSON summary path.",
    )
    args = parser.parse_args()

    log_dirs = args.log_dir or ["logs", "Logs"]
    summaries = [
        summary
        for path in discover_logs(log_dirs)
        if (summary := summarize_file(path)) is not None
    ]

    output = Path(args.output)
    write_markdown(summaries, output)
    print(f"Wrote {output}")

    if args.json_output:
        json_path = Path(args.json_output)
        json_path.parent.mkdir(parents=True, exist_ok=True)
        json_path.write_text(json.dumps(summaries, indent=2), encoding="utf-8")
        print(f"Wrote {json_path}")

    if not summaries:
        print("No metric rows found in training CSV logs.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
